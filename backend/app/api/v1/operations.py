import uuid

from fastapi import APIRouter, Depends
from sqlalchemy import select

from app.agents.planner import make_plan
from app.core.db import get_db
from app.core.deps import Principal, get_principal, require_role
from app.core.errors import AppError
from app.core.utils import get_scoped, to_dict
from app.models import Agent, AgentRun, Approval, WorkflowEvent, WorkflowNode
from app.schemas import OperationIn
from app.services.audit import audit
from app.services.events import emit_event
from app.workers.queue import enqueue_retry, enqueue_start

router = APIRouter(prefix="/operations", tags=["operations"])
ACTIVE = ("QUEUED", "PLANNING", "RUNNING", "WAITING_FOR_APPROVAL", "APPROVED", "EXECUTING", "VERIFYING", "RETRYING")


@router.post("/preview")
def preview(body: OperationIn, p: Principal = Depends(require_role("operator"))):
    """Plan preview shown to the user BEFORE anything executes."""
    return make_plan(p.org_id, None, body.request)


@router.post("")
def submit(body: OperationIn, p: Principal = Depends(require_role("operator")), db=Depends(get_db)):
    agent = db.scalar(select(Agent).where(Agent.org_id == p.org_id, Agent.key == "orchestrator"))
    run = AgentRun(org_id=p.org_id, user_id=p.user_id, agent_id=agent.id if agent else None,
                   request=body.request, status="QUEUED")
    db.add(run)
    db.flush()
    audit(db, p.org_id, p.user_id, "operation.submitted", "agent_run", run.id, run.id, {"request": body.request[:500]})
    db.commit()
    emit_event(p.org_id, run.id, "run.queued", None, "QUEUED", {})
    enqueue_start(str(run.id), p.role)  # only after commit so the worker can see the row
    return to_dict(run)


@router.get("")
def list_runs(status: str | None = None, limit: int = 50, offset: int = 0,
              p: Principal = Depends(get_principal), db=Depends(get_db)):
    q = select(AgentRun).where(AgentRun.org_id == p.org_id)
    if status:
        q = q.where(AgentRun.status == status)
    rows = db.scalars(q.order_by(AgentRun.created_at.desc()).limit(min(limit, 200)).offset(offset))
    return [to_dict(r) for r in rows]


@router.get("/{run_id}")
def detail(run_id: uuid.UUID, p: Principal = Depends(get_principal), db=Depends(get_db)):
    run = get_scoped(db, AgentRun, run_id, p.org_id)
    nodes = db.scalars(select(WorkflowNode).where(WorkflowNode.run_id == run.id, WorkflowNode.org_id == p.org_id)
                       .order_by(WorkflowNode.started_at))
    appr = db.scalars(select(Approval).where(Approval.run_id == run.id, Approval.org_id == p.org_id))
    return {**to_dict(run), "nodes": [to_dict(n) for n in nodes], "approvals": [to_dict(a) for a in appr]}


@router.get("/{run_id}/graph")
def graph(run_id: uuid.UUID, p: Principal = Depends(get_principal), db=Depends(get_db)):
    """Mission Canvas payload: nodes + edges generated by the backend."""
    run = get_scoped(db, AgentRun, run_id, p.org_id)
    nmap = {n.node_key: n for n in db.scalars(select(WorkflowNode).where(WorkflowNode.run_id == run.id))}
    steps = [{"key": "user_instruction", "agent": "User", "description": run.request}] + (run.plan or {}).get("steps", [])
    nodes, edges = [], []
    for i, s in enumerate(steps):
        n = nmap.get(s["key"])
        status = "completed" if s["key"] == "user_instruction" else (n.status if n else "pending")
        nodes.append({"id": s["key"], "label": s["description"], "agent": s["agent"], "status": status,
                      "duration_ms": n.duration_ms if n else None, "attempts": n.attempts if n else 0})
        if i:
            edges.append({"id": f"e{i}", "source": steps[i - 1]["key"], "target": s["key"],
                          "animated": status == "running"})
    return {"run_id": run.id, "status": run.status, "nodes": nodes, "edges": edges}


@router.get("/{run_id}/events")
def events(run_id: uuid.UUID, limit: int = 500, p: Principal = Depends(get_principal), db=Depends(get_db)):
    get_scoped(db, AgentRun, run_id, p.org_id)
    rows = db.scalars(select(WorkflowEvent).where(WorkflowEvent.run_id == run_id, WorkflowEvent.org_id == p.org_id)
                      .order_by(WorkflowEvent.created_at).limit(min(limit, 2000)))
    return [to_dict(e) for e in rows]


@router.post("/{run_id}/cancel")
def cancel(run_id: uuid.UUID, p: Principal = Depends(require_role("operator")), db=Depends(get_db)):
    run = get_scoped(db, AgentRun, run_id, p.org_id)
    if run.status not in ACTIVE:
        raise AppError(409, "not_cancellable", f"Run is {run.status}")
    run.status = "CANCELLED"
    for a in db.scalars(select(Approval).where(Approval.run_id == run.id, Approval.status == "pending")):
        a.status = "rejected"
        a.decision_note = "Run cancelled"
    audit(db, p.org_id, p.user_id, "operation.cancelled", "agent_run", run.id, run.id)
    db.commit()
    emit_event(p.org_id, run.id, "run.status", None, "CANCELLED", {})
    return {"ok": True}


@router.post("/{run_id}/retry")
def retry(run_id: uuid.UUID, p: Principal = Depends(require_role("operator")), db=Depends(get_db)):
    run = get_scoped(db, AgentRun, run_id, p.org_id)
    if run.status != "FAILED":
        raise AppError(409, "not_retryable", "Only FAILED runs can be retried")
    run.status, run.error, run.finished_at = "RETRYING", None, None
    audit(db, p.org_id, p.user_id, "operation.retried", "agent_run", run.id, run.id)
    db.commit()
    emit_event(p.org_id, run.id, "run.status", None, "RETRYING", {})
    enqueue_retry(str(run.id))
    return {"ok": True}
